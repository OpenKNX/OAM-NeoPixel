<#
.SYNOPSIS
    OpenKNX NeoPixel - host test: compiled-in effects, effect mapping, Web UI availability and the KNX
    effect-number guard agree for every effect flag set.

.DESCRIPTION
    Compiles the production EffectPool.cpp, src/EffectTypeMapping.h and
    src/WebUi/NeoPixelEffectCatalog.generated.h with one stub class per effect (the class carries its
    number from src/EffectIds.lock) for these flag sets: none, NEOPIXEL_DISABLE_2D (19..32 out),
    NEOPIXEL_MINIMAL_EFFECTS (8..18 out), both (8..32 out), NEOPIXEL_DISABLE_FIRE (8 out),
    NEOPIXEL_DISABLE_SCROLLTEXT (19 out). For every number 0..255 it checks:

      EffectPool::getEffectByIndex   the effect with that lock number, nullptr when compiled out or past the end;
      EffectPool::getEffectOrSolid   Solid for a compiled-out number, nullptr past the end;
      EffectPool::getEffectCount     all numbers, compiled-out ones included;
      getEffectFromType              the same effect, Solid for a compiled-out or unknown number;
      getTypeFromEffect              the number back for every compiled-in effect;
      NeoPixelEffectCatalog          isAvailable() true exactly for the compiled-in effects;
      KNX effect object              the guard block of NeoPixelBusModule::processInputKo (copied by its
                                     comment anchors) passes exactly the compiled-in numbers, restores
                                     _channelIndex on a refused number and leaves other objects alone;
      "Effekt schalten" (NEO_KoFxRel)  the stepping block of processInputKo (from the step-code read to the
                                     change check) goes to the next / previous compiled-in number for step
                                     codes 1..7, ignores step code 0 and stays on the first / last
                                     compiled-in effect (no wrap-around), with spot checks per flag set.

    processInputKo itself (about 1300 lines, the whole module state) is not compiled; the test checks by
    text that the guard sits after the channel lookup and before the first takeover (localOverride,
    interruptEmIfRunning) and before the effect is applied (case NEO_KoFx).

    Needs include/knxprod.h (generated by the OpenKNXproducer) for the PT_NEOEffectType enum.
    Sources are copied into a temporary folder, the repository is not changed.

.PARAMETER Root
    Repository root to read the sources from (default: the folder above this script).

.PARAMETER KeepTemp
    Keep the temporary folder (path in the output) for inspection.

.EXAMPLE
    pwsh test/Test-EffectAvailability.ps1

.NOTES
    Author: Erkan Colak
    Needs clang++ or g++ in PATH. On macOS with only the Command Line Tools set DEVELOPER_DIR to Xcode.
    Exit code: 0 = passed, 1 = check(s) failed or the build failed, 2 = compiler or source missing.
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)]
    [string]$Root = "",

    [Parameter(Mandatory = $false)]
    [switch]$KeepTemp
)

$ErrorActionPreference = 'Stop'

function OpenKNX_ShowLogo($AddCustomText = $null) {
    Write-Host ""
    Write-Host "Open " -NoNewline
    Write-Host "$( [char]::ConvertFromUtf32(0x25A0) )" -ForegroundColor Green
    $unicodeString = "$( [char]::ConvertFromUtf32(0x252C) )$( [char]::ConvertFromUtf32(0x2500) )$( [char]::ConvertFromUtf32(0x2500) )$( [char]::ConvertFromUtf32(0x2500) )$( [char]::ConvertFromUtf32(0x2500) )$( [char]::ConvertFromUtf32(0x2534) ) "
    if ($AddCustomText) { Write-Host "$($unicodeString) $($AddCustomText)" -ForegroundColor Green }
    else { Write-Host "$($unicodeString)" -ForegroundColor Green }
    Write-Host "$( [char]::ConvertFromUtf32(0x25A0) )" -NoNewline -ForegroundColor Green
    Write-Host " KNX"
    Write-Host ""
}

OpenKNX_ShowLogo "Effect Availability Test"

if (-not $Root) { $Root = Split-Path -Parent $PSScriptRoot }
$onWindows = [System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT
$utf8 = New-Object System.Text.UTF8Encoding($false)
$failures = 0

$paths = @{
    PoolH    = Join-Path $Root 'lib/OFM-NeoPixel/src/effects/EffectPool.h'
    PoolCpp  = Join-Path $Root 'lib/OFM-NeoPixel/src/effects/EffectPool.cpp'
    EffectH  = Join-Path $Root 'lib/OFM-NeoPixel/src/effects/Effect.h'
    ParamH   = Join-Path $Root 'lib/OFM-NeoPixel/src/effects/ParameterType.h'
    Mapping  = Join-Path $Root 'src/EffectTypeMapping.h'
    Catalog  = Join-Path $Root 'src/WebUi/NeoPixelEffectCatalog.generated.h'
    Lock     = Join-Path $Root 'src/EffectIds.lock'
    Module   = Join-Path $Root 'src/NeoPixelModule.cpp'
    Knxprod  = Join-Path $Root 'include/knxprod.h'
}

$cxx = $null
foreach ($name in @('clang++', 'g++')) {
    $cmd = Get-Command $name -ErrorAction SilentlyContinue
    if ($cmd) { $cxx = $cmd.Path; break }
}
if (-not $cxx) {
    Write-Host "MISSING: clang++ or g++ in PATH" -ForegroundColor Red
    exit 2
}
foreach ($key in $paths.Keys) {
    if (-not (Test-Path -LiteralPath $paths[$key] -PathType Leaf)) {
        $hint = ''
        if ($key -eq 'Knxprod') { $hint = ' - run scripts/Build-Release.ps1 first' }
        Write-Host "MISSING: $($paths[$key])$hint" -ForegroundColor Red
        exit 2
    }
}

# @brief Reads a text file with LF line ends
function Read-Text([string]$Path) {
    return ([System.IO.File]::ReadAllText($Path, $utf8)) -replace "`r`n", "`n"
}

# --- Effect numbers from the lock file: "<number><TAB><class><TAB><name>"
$lockIds = @{}
$numbers = 0
foreach ($line in ((Read-Text $paths.Lock) -split "`n")) {
    if ($line -match '^(\d+)\t(\w+)\t') {
        $lockIds[$Matches[2]] = [int]$Matches[1]
        if ([int]$Matches[1] + 1 -gt $numbers) { $numbers = [int]$Matches[1] + 1 }
    }
}
if ($numbers -eq 0) {
    Write-Host "FAIL: no effect numbers in $($paths.Lock)" -ForegroundColor Red
    exit 1
}

# --- Stub classes: every class EffectPool.h declares or EffectPool.cpp creates, with its lock number (255 = not in the lock)
$poolH = Read-Text $paths.PoolH
$poolCpp = Read-Text $paths.PoolCpp
$classes = @(@([regex]::Matches($poolH, '(?m)^class (\w+);') | ForEach-Object { $_.Groups[1].Value }) +
    @([regex]::Matches($poolCpp, '\bnew (\w+)\(\)') | ForEach-Object { $_.Groups[1].Value }) | Select-Object -Unique)
$stub = New-Object System.Text.StringBuilder
[void]$stub.Append("#pragma once`n#include `"Effect.h`"`n")
[void]$stub.Append("struct StubEffect : Effect {`n    uint8_t id;`n    explicit StubEffect(uint8_t number) : id(number) {}`n    void update(Segment*, uint32_t) override {}`n};`n")
foreach ($class in $classes) {
    $id = 255
    if ($lockIds.ContainsKey($class)) { $id = $lockIds[$class] }
    [void]$stub.Append("class $class : public StubEffect { public: $class() : StubEffect($id) {} };`n")
}
$poolIncludes = @([regex]::Matches($poolCpp,'(?m)^\s*#include "(\w+)\.h"') |
    ForEach-Object { $_.Groups[1].Value } | Where-Object { $_ -ne 'EffectPool' })

# --- PT_NEOEffectType from the generated product header
$enumMatch = [regex]::Match((Read-Text $paths.Knxprod), 'enum class PT_NEOEffectType\s*\{[^}]*\};')
if (-not $enumMatch.Success) {
    Write-Host "FAIL: enum PT_NEOEffectType not found in $($paths.Knxprod)" -ForegroundColor Red
    exit 1
}

# --- KNX effect-number guard of processInputKo, copied by its comment anchors
$module = Read-Text $paths.Module
$guardStartText = '        // An unknown or disabled effect ID maps to Solid'
$guardEndText = '        // A scene number not configured on this segment'
$fnStart = $module.IndexOf('void NeoPixelBusModule::processInputKo(')
$fnEnd = if ($fnStart -ge 0) { $module.IndexOf("`n}`n", $fnStart) } else { -1 }
$guardStart = if ($fnStart -ge 0) { $module.IndexOf($guardStartText, $fnStart) } else { -1 }
$guardEnd = if ($guardStart -ge 0) { $module.IndexOf($guardEndText, $guardStart) } else { -1 }
if ($fnStart -lt 0 -or $fnEnd -lt 0 -or $guardStart -lt 0 -or $guardEnd -lt 0 -or $guardStart -gt $fnEnd) {
    Write-Host "FAIL: effect-number guard of processInputKo not found by its anchors (src/NeoPixelModule.cpp changed?)" -ForegroundColor Red
    exit 1
}
$guard = $module.Substring($guardStart, $guardEnd - $guardStart)
if ($guard -notmatch 'koIndex == NEO_KoFx' -or $guard -notmatch 'isAvailable\(') {
    Write-Host "FAIL: the block between the guard anchors does not check NEO_KoFx with isAvailable()" -ForegroundColor Red
    $failures++
}

# --- "Effekt schalten" (NEO_KoFxRel) stepping of processInputKo: from the step-code read to the change check
$caseFxRel = $module.IndexOf('case NEO_KoFxRel:', $fnStart)
$stepStart = if ($caseFxRel -ge 0) { $module.IndexOf('uint8_t raw = ko.value(Dpt(5, 10));', $caseFxRel) } else { -1 }
$stepEnd = if ($stepStart -ge 0) { $module.IndexOf('if (next != cur)', $stepStart) } else { -1 }
if ($caseFxRel -lt 0 -or $stepStart -lt 0 -or $stepEnd -lt 0 -or $stepEnd -gt $fnEnd -or $module.IndexOf('case NEO_Ko', $caseFxRel + 10) -lt $stepEnd) {
    Write-Host "FAIL: NEO_KoFxRel stepping of processInputKo not found by its anchors (src/NeoPixelModule.cpp changed?)" -ForegroundColor Red
    exit 1
}
$step = $module.Substring($stepStart, $stepEnd - $stepStart)
if ($step -notmatch 'isAvailable\(') {
    Write-Host "FAIL: the NEO_KoFxRel stepping does not check isAvailable()" -ForegroundColor Red
    $failures++
}

# Order inside processInputKo: channel lookup < guard < first takeover (localOverride, EM stop) and effect switch
$channelPos = $module.IndexOf('int channel = NEO_KoCalcChannel(koNumber);', $fnStart)
if ($channelPos -lt 0 -or $channelPos -gt $guardStart) {
    Write-Host "FAIL: the guard does not follow the channel lookup in processInputKo" -ForegroundColor Red
    $failures++
}
else {
    $after = [ordered]@{
        'localOverride = true' = '_segments[channel].localOverride = true'
        'interruptEmIfRunning' = 'interruptEmIfRunning((size_t)channel);'
        'case NEO_KoFx'        = 'case NEO_KoFx:'
    }
    foreach ($name in $after.Keys) {
        # first occurrence after the channel lookup must follow the guard and lie inside processInputKo
        $pos = $module.IndexOf($after[$name], $channelPos)
        if ($pos -lt 0 -or $pos -gt $fnEnd) {
            Write-Host "FAIL: '$name' not found in processInputKo" -ForegroundColor Red
            $failures++
        }
        elseif ($pos -lt $guardStart) {
            Write-Host "FAIL: '$name' comes before the effect-number guard in processInputKo" -ForegroundColor Red
            $failures++
        }
    }
}
if ($failures -eq 0) { Write-Host "PASS: effect-number guard sits after the channel lookup and before the first takeover and the effect switch" }

$testSource = @'
#include <cstdio>
#include <cstdint>
#include "PT_NEOEffectType.h"
#include "src/EffectTypeMapping.h"
#include "src/WebUi/NeoPixelEffectCatalog.generated.h"
#include "lib/OFM-NeoPixel/src/effects/StubEffects.h"
#include "expected.h"

// Doubles for the names the guard block uses
#define DPT_Value_1_Ucount 0
#define logWarningP(...) ((void)0)
enum { NEO_KoFx = 1000, NEO_KoOther = 1001 };
struct KoDouble { uint8_t v; uint8_t value(int) const { return v; } };
inline int Dpt(int, int) { return 0; }
struct SegmentDouble { Effect* effect; Effect* getEffect() const { return effect; } };
// NEO_KoFxRel: effect number after one step telegram; 255 = no command (step code 0)
static uint8_t stepFx(uint8_t telegram, uint8_t running)
{
    KoDouble ko{telegram};
    SegmentDouble segment{getEffectFromType(running)};
    SegmentDouble* targetSegment = &segment;
#include "step.inc"
        return next;
    }
    return 255;
}
struct GuardHost {
    uint8_t _channelIndex = 0;
    bool passed = false;
    void run(KoDouble& ko, int koIndex, int channel, uint8_t oldChannelIndex)
    {
        passed = false;
        _channelIndex = channel;
#include "guard.inc"
        passed = true;
    }
};

static int failures = 0;
#define CHECK(e) do { if (!(e)) { std::fprintf(stderr, "%s: number %u: check failed: %s\n", kCase, n, #e); ++failures; } } while (0)

static uint8_t number(Effect* e)
{
    StubEffect* s = dynamic_cast<StubEffect*>(e);
    return s ? s->id : 255;
}

int main()
{
    const unsigned numbers = sizeof(kExpected) - 1;
    unsigned n = 0;
    CHECK(EffectPool::getEffectCount() == numbers);
    Effect* solid = EffectPool::getSolid();
    CHECK(solid && number(solid) == 0);
    for (n = 0; n < 256; ++n)
    {
        const uint8_t id = uint8_t(n);
        const bool expected = n < numbers && kExpected[n] == '1';
        Effect* e = EffectPool::getEffectByIndex(id);
        CHECK((e != nullptr) == expected);
        if (e) CHECK(number(e) == n);
        CHECK(NeoPixelEffectCatalog::isAvailable(id) == expected);
        CHECK(EffectPool::getEffectOrSolid(id) == (expected ? e : (n < numbers ? solid : nullptr)));
        Effect* mapped = getEffectFromType(id);
        CHECK(mapped == (expected ? e : solid));
        if (expected) CHECK(getTypeFromEffect(mapped) == n);
        GuardHost host;
        KoDouble ko{id};
        host.run(ko, NEO_KoFx, 2, 5);
        CHECK(host.passed == expected);
        if (!expected) CHECK(host._channelIndex == 5);
        host.run(ko, NEO_KoOther, 2, 5);
        CHECK(host.passed);
        if (expected)
        {
            // next / previous compiled-in number, the running one at either end (no wrap-around)
            unsigned up = n, down = n;
            for (unsigned k = n + 1; k < numbers; ++k) if (kExpected[k] == '1') { up = k; break; }
            for (int k = int(n) - 1; k >= 0; --k) if (kExpected[k] == '1') { down = unsigned(k); break; }
            for (uint8_t code = 1; code <= 7; ++code)
            {
                CHECK(stepFx(uint8_t(0x08 | code), id) == up);
                CHECK(stepFx(code, id) == down);
            }
            CHECK(stepFx(0x08, id) == 255);
            CHECK(stepFx(0x00, id) == 255);
        }
    }
    for (const auto& c : kStepChecks)
    {
        n = c[0];
        CHECK(stepFx(uint8_t(c[1]), uint8_t(c[0])) == c[2]);
    }
    if (failures) { std::fprintf(stderr, "%s: %d check(s) failed\n", kCase, failures); return 1; }
    return 0;
}
'@

$cases = @(
    @{ Name = 'full';                   Defines = @();                                                  Out = @();      Steps = '{32,0x09,32},{0,0x01,0},{18,0x09,19}' },
    @{ Name = 'NEOPIXEL_DISABLE_2D';    Defines = @('NEOPIXEL_DISABLE_2D');                             Out = @(19..32); Steps = '{18,0x09,18},{0,0x01,0},{17,0x09,18},{18,0x0f,18}' },
    @{ Name = 'NEOPIXEL_MINIMAL';       Defines = @('NEOPIXEL_MINIMAL_EFFECTS');                        Out = @(8..18);  Steps = '{7,0x09,19},{19,0x01,7}' },
    @{ Name = 'NEOPIXEL_MINIMAL+2D';    Defines = @('NEOPIXEL_MINIMAL_EFFECTS', 'NEOPIXEL_DISABLE_2D'); Out = @(8..32);  Steps = '{7,0x09,7},{0,0x01,0}' },
    @{ Name = 'NEOPIXEL_DISABLE_FIRE';  Defines = @('NEOPIXEL_DISABLE_FIRE');                           Out = @(8);      Steps = '{7,0x09,9},{9,0x01,7}' },
    @{ Name = 'NEOPIXEL_DISABLE_SCROLLTEXT'; Defines = @('NEOPIXEL_DISABLE_SCROLLTEXT');                Out = @(19);     Steps = '{18,0x09,20},{20,0x01,18}' }
)

$tempRoot = Join-Path ([System.IO.Path]::GetTempPath()) ("neopixel-availability-test-" + [Guid]::NewGuid().ToString('N').Substring(0, 8))
try {
    $effectsDir = Join-Path $tempRoot 'lib/OFM-NeoPixel/src/effects'
    New-Item -ItemType Directory -Path $effectsDir -Force | Out-Null
    New-Item -ItemType Directory -Path (Join-Path $tempRoot 'src/WebUi') -Force | Out-Null
    [System.IO.File]::Copy($paths.PoolH, (Join-Path $effectsDir 'EffectPool.h'), $true)
    [System.IO.File]::Copy($paths.PoolCpp, (Join-Path $effectsDir 'EffectPool.cpp'), $true)
    [System.IO.File]::Copy($paths.EffectH, (Join-Path $effectsDir 'Effect.h'), $true)
    [System.IO.File]::Copy($paths.ParamH, (Join-Path $effectsDir 'ParameterType.h'), $true)
    [System.IO.File]::Copy($paths.Mapping, (Join-Path $tempRoot 'src/EffectTypeMapping.h'), $true)
    [System.IO.File]::Copy($paths.Catalog, (Join-Path $tempRoot 'src/WebUi/NeoPixelEffectCatalog.generated.h'), $true)
    [System.IO.File]::WriteAllText((Join-Path $effectsDir 'StubEffects.h'), $stub.ToString(), $utf8)
    foreach ($include in $poolIncludes) {
        [System.IO.File]::WriteAllText((Join-Path $effectsDir "$include.h"), "#pragma once`n#include `"StubEffects.h`"`n", $utf8)
    }
    [System.IO.File]::WriteAllText((Join-Path $tempRoot 'PT_NEOEffectType.h'), "#pragma once`n" + $enumMatch.Value + "`n", $utf8)
    [System.IO.File]::WriteAllText((Join-Path $tempRoot 'guard.inc'), $guard, $utf8)
    [System.IO.File]::WriteAllText((Join-Path $tempRoot 'step.inc'), $step, $utf8)
    [System.IO.File]::WriteAllText((Join-Path $tempRoot 'test.cpp'), $testSource, $utf8)

    foreach ($case in $cases) {
        $mask = New-Object System.Text.StringBuilder
        for ($i = 0; $i -lt $numbers; $i++) { [void]$mask.Append($(if ($case.Out -contains $i) { '0' } else { '1' })) }
        [System.IO.File]::WriteAllText((Join-Path $tempRoot 'expected.h'),
            "#pragma once`nstatic const char kCase[] = `"$($case.Name)`";`nstatic const char kExpected[] = `"$($mask.ToString())`";`nstatic const unsigned kStepChecks[][3] = { $($case.Steps) };`n", $utf8)
        $exe = Join-Path $tempRoot 'availability-test'
        if ($onWindows) { $exe += '.exe' }
        $compileArgs = @('-std=c++17', '-I', $tempRoot) + @($case.Defines | ForEach-Object { "-D$_" }) +
            @((Join-Path $tempRoot 'test.cpp'), (Join-Path $effectsDir 'EffectPool.cpp'), '-o', $exe)
        if (-not $onWindows) { $compileArgs = @('-fsanitize=address,undefined', '-fno-omit-frame-pointer') + $compileArgs }

        $prev = $ErrorActionPreference
        $ErrorActionPreference = 'Continue'
        $runCode = -1
        & $cxx @compileArgs
        $buildCode = $LASTEXITCODE
        if ($buildCode -eq 0) {
            & $exe
            $runCode = $LASTEXITCODE
        }
        $ErrorActionPreference = $prev

        if ($buildCode -ne 0) { Write-Host "FAIL: $($case.Name): build (exit $buildCode)" -ForegroundColor Red; $failures++ }
        elseif ($runCode -ne 0) { Write-Host "FAIL: $($case.Name): checks (exit $runCode)" -ForegroundColor Red; $failures++ }
        else { Write-Host "PASS: $($case.Name): pool, mapping, availability, KNX guard and effect stepping agree ($($mask.ToString()))" }
    }
}
finally {
    if ($KeepTemp) { Write-Host "Temporary folder kept: $tempRoot" }
    else { Remove-Item -LiteralPath $tempRoot -Recurse -Force -ErrorAction SilentlyContinue }
}

if ($failures -gt 0) {
    Write-Host "$failures failure(s)" -ForegroundColor Red
    exit 1
}
exit 0
